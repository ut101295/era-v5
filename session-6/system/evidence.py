"""Evidence bundle: evidence.json + evidence.md, generated from live checks.

Nothing here decides a result. `run_demo.py` calls `check(...)` with a boolean
it has just computed from the artifacts (ledgers, manifests, hashes), plus the
measured values behind it. A requirement passes only if every one of its checks
passed and it has at least one check, so a skipped section shows up as FAIL
rather than silently passing.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any, Dict, List

# (id, row label in evidence.md, what the evidence column points at)
REQUIREMENTS = [
    ("tokenizer_integrity", "Tokenizer integrity", "Tokenizer record + shard manifests"),
    ("shard_immutability", "Shards, manifests and admission", "Shard manifests + admission log"),
    ("evaluation_firewall", "Evaluation firewall", "Blocked-shard events + post-run scan"),
    ("packing_correctness", "Packing correctness", "Packed-batch report"),
    ("mixture_compliance", "Mixture compliance", "Planned versus actual shares"),
    ("opus_audit_trail", "OPUS audit trail", "Candidate decision records"),
    ("checkpoint_binding", "Checkpoints tied to ledger offsets", "Checkpoint index"),
    ("crash_recovery", "Crash recovery", "Expected and resumed batch ids"),
    ("replay", "Replay", "Original and replay hashes"),
    ("fork", "Fork from earlier checkpoint", "Fork lineage record"),
    ("learning_trace", "Learning trace", "Loss linked to source data"),
    ("throughput", "Throughput", "Performance report"),
]


@dataclass
class Check:
    name: str
    passed: bool
    detail: Dict[str, Any] = field(default_factory=dict)


class Evidence:
    def __init__(self):
        self.checks: Dict[str, List[Check]] = {rid: [] for rid, _, _ in REQUIREMENTS}
        self.paths: Dict[str, List[str]] = {rid: [] for rid, _, _ in REQUIREMENTS}

    def check(self, requirement: str, name: str, passed: bool, log=None, **detail) -> bool:
        assert requirement in self.checks, f"unknown requirement {requirement}"
        passed = bool(passed)
        self.checks[requirement].append(Check(name, passed, detail))
        if log is not None:
            log(f"[{'PASS' if passed else 'FAIL'}] {name}")
        return passed

    def point(self, requirement: str, *paths: str) -> None:
        for p in paths:
            if p not in self.paths[requirement]:
                self.paths[requirement].append(p)

    def result(self, requirement: str) -> str:
        cs = self.checks[requirement]
        return "PASS" if cs and all(c.passed for c in cs) else "FAIL"

    def all_passed(self) -> bool:
        return all(self.result(rid) == "PASS" for rid, _, _ in REQUIREMENTS)

    # ------------------------------------------------------------- writers
    def to_dict(self, run_info: Dict) -> Dict:
        return {
            "run": run_info,
            "overall": "PASS" if self.all_passed() else "FAIL",
            "requirements": [
                {
                    "id": rid, "requirement": label, "result": self.result(rid),
                    "evidence": self.paths[rid],
                    "checks": [{"name": c.name, "passed": c.passed, "detail": c.detail}
                               for c in self.checks[rid]],
                }
                for rid, label, _ in REQUIREMENTS
            ],
        }

    def write(self, json_path: str, md_path: str, run_info: Dict) -> None:
        data = self.to_dict(run_info)
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(self._markdown(data))

    def _markdown(self, data: Dict) -> str:
        run = data["run"]
        lines = [
            "# Evidence summary",
            "",
            f"Generated by `{run['command']}`. Overall: **{data['overall']}** "
            f"({sum(r['result'] == 'PASS' for r in data['requirements'])}/"
            f"{len(data['requirements'])} requirements).",
            "",
            "| Requirement | Result | Evidence |",
            "| --- | --- | --- |",
        ]
        labels = {rid: ev for rid, _, ev in REQUIREMENTS}
        for r in data["requirements"]:
            files = ", ".join(f"`{p}`" for p in r["evidence"])
            n = len(r["checks"])
            ok = sum(c["passed"] for c in r["checks"])
            lines.append(f"| {r['requirement']} | {r['result']} | "
                         f"{labels[r['id']]}: {files} ({ok}/{n} checks) |")
        lines += ["", "## Checks", ""]
        for r in data["requirements"]:
            lines.append(f"### {r['requirement']} — {r['result']}")
            lines.append("")
            for c in r["checks"]:
                lines.append(f"- **{'PASS' if c['passed'] else 'FAIL'}** `{c['name']}`"
                             + (f" — {_fmt(c['detail'])}" if c["detail"] else ""))
            lines.append("")
        lines += [
            "## Run",
            "",
            *[f"- {k}: `{v}`" for k, v in run.items()],
            "",
        ]
        return "\n".join(lines)


def _fmt(detail: Dict) -> str:
    parts = []
    for k, v in detail.items():
        s = json.dumps(v, ensure_ascii=False)
        if len(s) > 120:
            s = s[:117] + "..."
        parts.append(f"{k}={s}")
    return ", ".join(parts)
